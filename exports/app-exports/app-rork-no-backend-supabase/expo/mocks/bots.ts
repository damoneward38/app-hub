export const featuredBots = bots.filter(bot => bot.isFeatured);
export const newBots = bots.filter(bot => bot.isNew);

export const getBotsByCategory = (category: string): Bot[] => {
  if (category === 'All') return bots;
  return bots.filter(bot => bot.category === category);
};

export const getBotById = (id: string): Bot | undefined => {
  return bots.find(bot => bot.id === id);
};
