#!/usr/bin/env python3
"""houly-pipe — config-driven long-form render pipeline.

    raw/*.mp4  →  trim + normalise  →  one filtergraph  →  master  →  YouTube

Stages
  1. trim     each scene is cut and normalised to identical res/fps/pix_fmt/audio
              (xfade and concat both refuse to join streams that disagree)
  2. render   ONE ffmpeg invocation: xfade/acrossfade chain, LUT, scale+pad,
              burned subtitles, watermark, fade to black, final encode
  3. preview  10s head clip (stream-copied) + a JPEG thumbnail
  4. upload   resumable YouTube Data API v3 upload

Why two encodes and not one: seeking inside 4K sources inside a 20-input
filtergraph makes ffmpeg hold every decoder open at once, and one bad frame kills
a four-hour job with nothing to resume from. Normalising first makes stage 2
restartable and lets `--stages render` re-grade without re-cutting.

  python3 scripts/pipeline.py --config config.yaml
  python3 scripts/pipeline.py --dry-run          # print every command, run none
  python3 scripts/pipeline.py --stages render    # re-render from existing tmp/
  python3 scripts/pipeline.py --limit 30         # 30s master, for a fast check
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent))

from utils import (  # noqa: E402
    PipelineError, ensure_dir, escape_filter_value, human_size, load_config,
    parse_time, probe, require_tools, resolve, run_ffmpeg, set_progress_hook,
    timecode,
)

ALL_STAGES = ("composite", "trim", "render", "preview", "upload")

# Share of total wall time per stage, measured across real runs. The Intégrav
# app uses the same weights, so a job reads identically in both places.
# Compositing is per-frame Python, so it is dear next to an ffmpeg-only stage;
# overall() renormalises across whichever stages a run actually executes.
STAGE_WEIGHTS = {"composite": 0.30, "trim": 0.24, "render": 0.60,
                 "preview": 0.04, "upload": 0.12}

# Every knob the composite stage accepts, with the default green_machine uses.
# Unknown keys are rejected rather than ignored: a config is generated by the
# phone, and silently dropping a misspelled key would have the operator staring
# at a setting that never took effect.
COMPOSITE_DEFAULTS: dict[str, Any] = {
    "background": None,
    "matte": "chroma",
    "keyColor": "green",
    "tolerance": 0.16,
    "softness": 0.08,
    "despill": 0.8,
    "feather": 2,
    "size": 1.0,
    "rotate": 0.0,
    "x": 0.0,
    "y": 0.0,
    "blend": 1.0,
}

# xfade styles worth exposing; ffmpeg has ~50 more, any of them work here.
XFADE_STYLES = {
    "fade", "fadeblack", "fadewhite", "dissolve", "wipeleft", "wiperight",
    "wipeup", "wipedown", "slideleft", "slideright", "slideup", "slidedown",
    "circleopen", "circleclose", "radial", "smoothleft", "smoothright", "pixelize",
}


