@dataclass(frozen=True)
class Transition:
    """How scene N joins scene N+1. On the last scene it means 'fade to black'."""
    kind: str = "cut"
    duration: float = 0.0

    @classmethod
    def parse(cls, value: Any) -> "Transition":
        if value in (None, "", "cut", "none"):
            return cls()
        parts = str(value).split()
        style = parts[0].lower()
        if style == "cut":
            return cls()
        if style not in XFADE_STYLES:
            raise PipelineError(
                f"Unknown transition {style!r}. Use 'cut' or one of: "
                f"{', '.join(sorted(XFADE_STYLES))}"
            )
        duration = parse_time(parts[1]) if len(parts) > 1 else 1.0
        return cls(style, max(0.05, duration))

    @property
    def is_cut(self) -> bool:
        return self.kind == "cut" or self.duration <= 0.0


@dataclass
class Scene:
    id: str
    source: Path
    start: float
    duration: float
    transition: Transition
    info: dict[str, Any] = field(default_factory=dict)
    normalized: Path | None = None
    # Green-screen settings for this scene, if it has any.
    composite: dict[str, Any] | None = None

    def adopt_keyed(self, keyed: Path) -> None:
        """Point the scene at its composited clip.

        The keyed file already covers exactly the requested window, so the
        in-point resets to zero — leaving `start` alone would cut the same
        offset twice and the scene would begin late.
        """
        info = probe(keyed)
        self.source = keyed
        self.start = 0.0
        self.duration = min(self.duration, info["duration"]) or info["duration"]
        self.info = info


def build_scenes(config: dict[str, Any], root: Path) -> list[Scene]:
    segments = config.get("sceneSegments") or []
    if not segments:
        raise PipelineError("config.sceneSegments is empty — nothing to render.")

    scenes: list[Scene] = []
    seen: set[str] = set()
    for index, segment in enumerate(segments):
        scene_id = str(segment.get("id") or f"scene{index:02d}")
        if scene_id in seen:
            raise PipelineError(f"Duplicate scene id {scene_id!r}.")
        seen.add(scene_id)

        if not segment.get("file"):
            raise PipelineError(f"Scene {scene_id!r} has no `file`.")
        # `file:` is relative to the config, not hardcoded to raw/ — so a scene can
        # live anywhere, including a previous render in out/.
        source = resolve(root, segment["file"])
        info = probe(source)
        if not info["has_video"]:
            raise PipelineError(f"Scene {scene_id!r}: {source.name} has no video stream.")

        start = parse_time(segment.get("start", 0))
        if segment.get("duration") is not None:
            duration = parse_time(segment["duration"])
        elif segment.get("end") is not None:
            duration = parse_time(segment["end"]) - start
        else:
            duration = info["duration"] - start

        available = info["duration"] - start
        if start < 0 or available <= 0:
            raise PipelineError(
                f"Scene {scene_id!r}: start {timecode(start)} is beyond the "
                f"source ({timecode(info['duration'])})."
            )
        if duration <= 0:
            raise PipelineError(f"Scene {scene_id!r}: end must be after start.")
        if duration > available + 0.05:
            print(f"  ! {scene_id}: clipped to source end "
                  f"({timecode(duration)} → {timecode(available)})")
            duration = available

        scenes.append(Scene(
            id=scene_id,
            source=source,
            start=start,
            duration=duration,
            transition=Transition.parse(segment.get("transition")),
            info=info,
            composite=parse_composite(segment.get("composite"), scene_id),
        ))
    return scenes


def parse_composite(value: Any, scene_id: str) -> dict[str, Any] | None:
    """Validate a scene's green-screen block and fill in the defaults."""
    if value in (None, False):
        return None
    if not isinstance(value, dict):
        raise PipelineError(
            f"Scene {scene_id!r}: `composite` must be a block of settings, "
            f"not {type(value).__name__}."
        )

    unknown = sorted(set(value) - set(COMPOSITE_DEFAULTS))
    if unknown:
        raise PipelineError(
            f"Scene {scene_id!r}: unknown composite setting(s) {', '.join(unknown)}. "
            f"Valid keys: {', '.join(sorted(COMPOSITE_DEFAULTS))}"
        )

    settings = {**COMPOSITE_DEFAULTS, **value}
    if not settings["background"]:
        raise PipelineError(
            f"Scene {scene_id!r}: composite needs a `background` — an image, a "
            f"video, or a colour like '#101018'."
        )
    if settings["matte"] not in ("chroma", "person"):
        raise PipelineError(
            f"Scene {scene_id!r}: composite.matte must be 'chroma' or 'person' "
            f"(got {settings['matte']!r})."
        )

    for key in ("tolerance", "softness", "despill", "blend"):
        number = float(settings[key])
        if not 0.0 <= number <= 1.0:
            raise PipelineError(
                f"Scene {scene_id!r}: composite.{key} must be between 0 and 1 "
                f"(got {number:g})."
            )
        settings[key] = number
    for key in ("size", "rotate", "x", "y"):
        settings[key] = float(settings[key])
    if settings["size"] <= 0:
        raise PipelineError(
            f"Scene {scene_id!r}: composite.size must be greater than 0 "
            f"(got {settings['size']:g})."
        )
    settings["feather"] = int(settings["feather"])
    if settings["feather"] < 0:
        raise PipelineError(f"Scene {scene_id!r}: composite.feather cannot be negative.")
    return settings


def preflight_assets(pipe: dict[str, Any], root: Path) -> None:
    """Check the optional look assets before a single frame is encoded.

    These are only read in stage 2, so without this a four-hour job spends the
    whole trim stage working and then dies on a missing watermark. Everything
    missing is reported at once, so the operator fixes one list instead of
    rediscovering the next gap on the next run.
    """
    wanted = (
        ("lut", "LUT", "applyLUT"),
        ("logo", "Watermark", "watermark"),
        ("subtitles", "Subtitle file", "burnSubtitles"),
    )
    missing: list[str] = []
    for key, label, toggle in wanted:
        value = pipe.get(key)
        if not value:
            continue
        path = resolve(root, value)
        if not path.is_file():
            missing.append(f"  {label}: {path}\n    (remove `{key}:` from the config, "
                          f"or turn off {toggle} in the render panel)")
    if missing:
        raise PipelineError(
            "The render is configured to use files that are not on this computer:\n"
            + "\n".join(missing)
        )


def load_green_machine() -> Any:
    """Import the compositor only when a job actually asks for it.

    A render-only host needs nothing but FFmpeg; importing OpenCV at module
    scope would make every plain render fail on a machine that will never key
    a single frame.
    """
    try:
        import green_machine  # noqa: PLC0415 - deliberately lazy
    except ImportError as error:
        raise PipelineError(
            "The composite stage needs OpenCV and NumPy, which are not "
            "installed on this computer.\n"
            "  Install them:  pip install opencv-python numpy\n"
            "  Or turn the green screen off in the render panel and re-send "
            "the job."
        ) from error
    return green_machine


def preflight_composites(scenes: list[Scene], root: Path) -> None:
    """Check every background and key colour before the first frame is keyed.

    Compositing is the slowest stage, so a mistyped background must not
    surface only after scene one has already been through it.
    """
    keyed = [scene for scene in scenes if scene.composite]
    if not keyed:
        return

    green_machine = load_green_machine()
    problems: list[str] = []
    for scene in keyed:
        settings = scene.composite or {}
        spec = str(settings["background"])
        path = resolve(root, spec)
        looks_like_colour = (
            spec.startswith("#") or "," in spec
            or spec.lower() in green_machine.NAMED_COLORS
        )
        if looks_like_colour and not path.exists():
            try:
                green_machine.parse_color(spec)
            except PipelineError as error:
                problems.append(f"  {scene.id}: background - {error}")
        elif not path.is_file():
            problems.append(
                f"  {scene.id}: background not found: {path}\n"
                f"    (choose a file that exists, or a colour like '#101018')"
            )
        try:
            green_machine.parse_color(str(settings["keyColor"]))
        except PipelineError as error:
            problems.append(f"  {scene.id}: keyColor - {error}")

    if problems:
        raise PipelineError(
            "The green screen is configured with things this computer cannot "
            "use:\n" + "\n".join(problems)
        )


