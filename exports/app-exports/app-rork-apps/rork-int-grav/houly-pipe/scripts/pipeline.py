def parse_resolution(value: Any) -> tuple[int, int]:
    text = str(value or "3840x2160").lower().replace("×", "x")
    try:
        width, _, height = text.partition("x")
        return int(width), int(height)
    except ValueError as error:
        raise PipelineError(f"Bad resolution {value!r}, expected e.g. 3840x2160") from error


def bitrate_to_k(value: Any) -> int | None:
    """'50M' / '50000k' / 50000000 → kilobits."""
    if value in (None, "", 0):
        return None
    text = str(value).strip().upper()
    try:
        if text.endswith("M"):
            return int(float(text[:-1]) * 1000)
        if text.endswith("K"):
            return int(float(text[:-1]))
        return int(float(text) / 1000)
    except ValueError as error:
        raise PipelineError(f"Bad bitrate {value!r}, expected e.g. 50M") from error


def video_encoder_args(pipe: dict[str, Any], *, intermediate: bool = False) -> list[str]:
    codec = str(pipe.get("codec", "libx264"))
    preset = str(pipe.get("preset", "medium"))
    crf = pipe.get("crf", 18)
    fps = float(pipe.get("fps", 60))

    if intermediate:
        codec, preset, crf = "libx264", "veryfast", pipe.get("intermediateCrf", 16)

    args: list[str] = ["-c:v", codec]
    if codec in {"libx264", "libx265"}:
        args += ["-preset", preset, "-crf", str(crf)]
        if codec == "libx265":
            args += ["-tag:v", "hvc1"]  # QuickTime/Finder refuse plain 'hev1'
    elif codec == "libaom-av1":
        args += ["-crf", str(crf), "-b:v", "0",
                 "-cpu-used", str(pipe.get("cpuUsed", 4)), "-row-mt", "1"]
    elif codec.endswith("_nvenc"):
        args += ["-preset", "p5", "-rc", "vbr", "-cq", str(crf), "-b:v", "0"]
    elif codec.endswith("_videotoolbox") or codec.endswith("_qsv") or codec.endswith("_vaapi"):
        # Hardware encoders have no CRF; they need an explicit target bitrate.
        kbps = bitrate_to_k(pipe.get("bitrate")) or 50_000
        args += ["-b:v", f"{kbps}k"]
    else:
        args += ["-crf", str(crf)]

    # Capped CRF: quality-driven, but never spikes past the delivery ceiling.
    if not intermediate and codec in {"libx264", "libx265"}:
        kbps = bitrate_to_k(pipe.get("bitrate"))
        if kbps:
            args += ["-maxrate", f"{kbps}k", "-bufsize", f"{kbps * 2}k"]

    keyint = max(2, int(round(fps * 2)))
    args += ["-g", str(keyint), "-keyint_min", str(keyint), "-sc_threshold", "0",
             "-pix_fmt", str(pipe.get("pixFmt", "yuv420p"))]
    if not intermediate:
        args += ["-color_primaries", "bt709", "-color_trc", "bt709", "-colorspace", "bt709"]
    return args


def audio_encoder_args(pipe: dict[str, Any]) -> list[str]:
    return ["-c:a", "aac", "-b:a", str(pipe.get("audioBitrate", "384k")),
            "-ar", "48000", "-ac", "2"]


def scale_pad(width: int, height: int) -> str:
    """Fit-inside-and-letterbox, so mixed-aspect sources never stretch."""
    return (f"scale={width}:{height}:force_original_aspect_ratio=decrease:flags=lanczos,"
            f"pad={width}:{height}:(ow-iw)/2:(oh-ih)/2:color=black,setsar=1")


