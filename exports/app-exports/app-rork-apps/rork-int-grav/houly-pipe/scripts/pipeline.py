def composite_fingerprint(scene: Scene, settings: dict[str, Any], root: Path) -> str:
    """Identity of a keyed clip: the window, the plate, and every knob.

    Same reasoning as the trim cache — nudging tolerance by 0.01 has to
    invalidate the cached key, or the operator changes a setting on the phone
    and gets the previous result back with no sign anything was ignored.
    """
    def stamp(path: Path) -> str:
        try:
            info = path.stat()
            return f"{info.st_size}:{int(info.st_mtime)}"
        except OSError:
            return "missing"

    background = resolve(root, str(settings["background"]))
    payload = "|".join(str(part) for part in (
        scene.source.resolve(), stamp(scene.source),
        round(scene.start, 3), round(scene.duration, 3),
        settings["background"], stamp(background),
        *(settings[key] for key in sorted(COMPOSITE_DEFAULTS) if key != "background"),
    ))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def stage_composite(scenes: list[Scene], pipe: dict[str, Any], tmp: Path, root: Path, *,
                    dry_run: bool, force: bool, step: str,
                    progress: Any = None) -> None:
    """Key each green-screen scene over its background before anything is cut.

    The keyed clip becomes the scene's source, so the rest of the pipeline
    (trim, transitions, LUT, watermark) is unchanged and unaware.
    """
    wanted = [scene for scene in scenes if scene.composite]
    print(f"\n▸ {step} · green screen ({len(wanted)} of {len(scenes)} scenes)")
    if not wanted:
        print("  · no scene asks for a composite — nothing to key")
        return

    green_machine = load_green_machine()
    for index, scene in enumerate(wanted, start=1):
        settings = scene.composite or {}
        target = tmp / f"{scene.id}.keyed.mp4"
        stamp_path = tmp / f"{scene.id}.keyed.json"
        fingerprint = composite_fingerprint(scene, settings, root)

        if dry_run:
            print(f"  [dry-run] {scene.id}: key {scene.source.name} over "
                  f"{settings['background']} → {target.name}")
            continue

        if target.is_file() and not force:
            try:
                cached = json.loads(stamp_path.read_text("utf-8")).get("fingerprint")
            except (OSError, ValueError, AttributeError):
                cached = None
            if cached == fingerprint:
                print(f"  · {scene.id}: cached")
                scene.adopt_keyed(target)
                continue
            print(f"  · {scene.id}: source or settings changed — re-keying")

        # A background that names a real file wins; anything else is a colour,
        # which green_machine resolves itself.
        background = resolve(root, str(settings["background"]))
        background_arg = (str(background) if background.is_file()
                          else str(settings["background"]))

        label = f"composite {index}/{len(wanted)} · {scene.id}"
        print(f"  ▸ {label}")
        options = argparse.Namespace(
            input=str(scene.source),
            bg=background_arg,
            output=str(target),
            matte=str(settings["matte"]),
            key_color=str(settings["keyColor"]),
            tolerance=settings["tolerance"],
            softness=settings["softness"],
            despill=settings["despill"],
            feather=settings["feather"],
            size=settings["size"],
            rotate=settings["rotate"],
            x=settings["x"],
            y=settings["y"],
            blend=settings["blend"],
            # Visually lossless: this clip is re-encoded again by stage 2, so a
            # delivery CRF here would stack two lots of loss.
            crf=int(pipe.get("intermediateCrf", 16)),
            preset="veryfast",
            fps=None,
            mute=False,
            limit=None,
            start=scene.start,
            duration=scene.duration,
        )

        def report(done: int, total: int, _label: str = label) -> None:
            if progress is not None:
                progress(_label, float(done), float(total) if total else None, "—")

        green_machine.run(options, on_progress=report)
        scene.adopt_keyed(target)

        try:
            stamp_path.write_text(json.dumps({
                "fingerprint": fingerprint,
                "source": str(scene.source),
                "background": str(settings["background"]),
            }, indent=2), encoding="utf-8")
        except OSError:
            pass  # a missing stamp only costs a re-key next run


def adopt_existing_keys(scenes: list[Scene], tmp: Path) -> None:
    """Reuse keyed clips when the composite stage is not part of this run.

    Without this, `--stages render` after a composite run would quietly go back
    to the original green footage.
    """
    for scene in scenes:
        if not scene.composite:
            continue
        keyed = tmp / f"{scene.id}.keyed.mp4"
        if keyed.is_file():
            scene.adopt_keyed(keyed)


