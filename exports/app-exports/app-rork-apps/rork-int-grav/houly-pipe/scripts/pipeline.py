class StatusWriter:
    """Writes `out/status.json` while the render runs.

    The dashboard polls this to show progress before `manifest.json` exists.
    Writes are throttled and atomic (temp file + replace) so a reader never
    catches a half-written file, and every failure is swallowed — status output
    must never be able to kill a render.
    """

    def __init__(self, path: Path, stages: Sequence[str], *, interval: float = 0.5) -> None:
        self.path = path
        self.stages = [stage for stage in ALL_STAGES if stage in stages]
        self.interval = interval
        self.started = time.time()
        self._last_write = 0.0
        self._total_weight = sum(STAGE_WEIGHTS[stage] for stage in self.stages) or 1.0

    @staticmethod
    def stage_for(label: str) -> str:
        """Map an ffmpeg run label back onto its pipeline stage."""
        if label.startswith("composite"):
            return "composite"
        if label.startswith("trim"):
            return "trim"
        if label.startswith("render"):
            return "render"
        if label.startswith(("preview", "thumbnail")):
            return "preview"
        if label.startswith("upload"):
            return "upload"
        return "render"

    def overall(self, stage: str, fraction: float) -> float:
        """Weighted progress across the stages this run will actually execute."""
        done = 0.0
        for candidate in self.stages:
            if candidate == stage:
                done += STAGE_WEIGHTS[candidate] * max(0.0, min(1.0, fraction))
                break
            done += STAGE_WEIGHTS[candidate]
        return round(min(1.0, done / self._total_weight), 4)

    def on_progress(self, label: str, done: float, total: float | None, speed: str) -> None:
        now = time.time()
        fraction = (done / total) if total and total > 0 else 0.0
        # Always flush the final frame of a stage, throttle everything else.
        if fraction < 1.0 and now - self._last_write < self.interval:
            return
        self._last_write = now
        stage = self.stage_for(label)
        self.write({
            "state": "running",
            "stage": stage,
            "label": label,
            "stageProgress": round(max(0.0, min(1.0, fraction)), 4),
            "progress": self.overall(stage, fraction),
            "speed": speed,
            "elapsedSeconds": round(now - self.started, 1),
        })

    def finish(self, state: str, message: str = "") -> None:
        self.write({
            "state": state,
            "stage": self.stages[-1] if self.stages else "render",
            "label": message,
            "stageProgress": 1.0 if state == "done" else 0.0,
            "progress": 1.0 if state == "done" else 0.0,
            "speed": "—",
            "elapsedSeconds": round(time.time() - self.started, 1),
        })

    def write(self, payload: dict[str, Any]) -> None:
        try:
            payload["updatedAt"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
            temp = self.path.with_suffix(".json.tmp")
            temp.write_text(json.dumps(payload, indent=2), encoding="utf-8")
            temp.replace(self.path)
        except OSError:
            pass


