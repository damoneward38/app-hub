def trim_fingerprint(scene: Scene, pipe: dict[str, Any], width: int, height: int, fps: float) -> str:
    """Identity of a normalised intermediate: every input that changes its bytes.

    Duration alone is not identity. Two different sources cut to the same length
    produce the same filename, so without this a swapped clip (or a second job
    reusing the same tmp/) would silently render the previous footage.
    """
    try:
        stat = scene.source.stat()
        stamp = f"{stat.st_size}:{int(stat.st_mtime)}"
    except OSError:
        stamp = "missing"
    payload = "|".join(str(part) for part in (
        scene.source.resolve(), stamp,
        round(scene.start, 3), round(scene.duration, 3),
        width, height, fps,
        pipe.get("intermediateCrf", pipe.get("crf", 18)),
        pipe.get("pixFmt", "yuv420p"),
        pipe.get("audioBitrate", "384k"),
    ))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def stage_trim(scenes: list[Scene], pipe: dict[str, Any], tmp: Path, *,
               dry_run: bool, force: bool, step: str) -> None:
    width, height = parse_resolution(pipe.get("resolution"))
    fps = float(pipe.get("fps", 60))

    print(f"\n▸ {step} · trim + normalise ({len(scenes)} scenes → {width}x{height} @ {fps:g}fps)")
    for index, scene in enumerate(scenes, start=1):
        target = tmp / f"{scene.id}.norm.mp4"
        stamp_path = tmp / f"{scene.id}.norm.json"
        scene.normalized = target
        fingerprint = trim_fingerprint(scene, pipe, width, height, fps)

        if target.is_file() and not force and not dry_run:
            try:
                cached = json.loads(stamp_path.read_text("utf-8")).get("fingerprint")
            except (OSError, ValueError, AttributeError):
                cached = None
            existing = probe(target)
            if cached == fingerprint and abs(existing["duration"] - scene.duration) < 0.35:
                print(f"  · {scene.id}: cached ({timecode(existing['duration'])})")
                continue
            print(f"  · {scene.id}: source or settings changed — re-cutting")

        args = ["-ss", f"{scene.start:.3f}", "-t", f"{scene.duration:.3f}",
                "-i", str(scene.source)]

        # A silent scene still needs an audio track, or concat/acrossfade
        # desynchronise everything downstream.
        if not scene.info["has_audio"]:
            args += ["-f", "lavfi", "-t", f"{scene.duration:.3f}",
                     "-i", "anullsrc=channel_layout=stereo:sample_rate=48000",
                     "-map", "0:v:0", "-map", "1:a:0"]
        else:
            args += ["-map", "0:v:0", "-map", "0:a:0"]

        args += ["-vf", f"fps={fps},{scale_pad(width, height)},format=yuv420p",
                 "-af", "aresample=async=1:first_pts=0"]
        args += video_encoder_args(pipe, intermediate=True)
        args += audio_encoder_args(pipe)
        args += ["-movflags", "+faststart", str(target)]

        run_ffmpeg(args, label=f"trim {index}/{len(scenes)} · {scene.id}",
                   total_seconds=scene.duration, dry_run=dry_run)

        if not dry_run:
            try:
                stamp_path.write_text(json.dumps({
                    "fingerprint": fingerprint,
                    "source": str(scene.source),
                    "start": round(scene.start, 3),
                    "duration": round(scene.duration, 3),
                }, indent=2), encoding="utf-8")
            except OSError:
                pass  # a missing stamp only costs a re-cut next run


# --------------------------------------------------------------------------- #
# stage 2 — one filtergraph, one encode
# --------------------------------------------------------------------------- #

def build_filtergraph(scenes: list[Scene], pipe: dict[str, Any], root: Path,
                      logo_index: int | None) -> tuple[str, float]:
    """Chain the scenes, then grade/scale/subtitle/watermark. Returns (graph, duration)."""
    width, height = parse_resolution(pipe.get("resolution"))
    fps = float(pipe.get("fps", 60))
    parts: list[str] = []

    v_label, a_label = "0:v", "0:a"
    total = scenes[0].duration

    for index in range(1, len(scenes)):
        transition = scenes[index - 1].transition
        scene = scenes[index]
        v_out, a_out = f"v{index}", f"a{index}"

        if transition.is_cut:
            parts.append(f"[{v_label}][{index}:v]concat=n=2:v=1:a=0[{v_out}]")
            parts.append(f"[{a_label}][{index}:a]concat=n=2:v=0:a=1[{a_out}]")
            total += scene.duration
        else:
            # An xfade longer than either side eats the whole clip; clamp it.
            duration = min(transition.duration, total - 0.05, scene.duration - 0.05)
            if duration <= 0:
                print(f"  ! {scenes[index - 1].id}→{scene.id}: clip too short for a "
                      f"{transition.duration:g}s {transition.kind}, using a cut")
                parts.append(f"[{v_label}][{index}:v]concat=n=2:v=1:a=0[{v_out}]")
                parts.append(f"[{a_label}][{index}:a]concat=n=2:v=0:a=1[{a_out}]")
                total += scene.duration
            else:
                if duration < transition.duration:
                    print(f"  ! {scenes[index - 1].id}→{scene.id}: transition clamped "
                          f"{transition.duration:g}s → {duration:.2f}s")
                # offset is where the overlap STARTS on the accumulated timeline
                offset = max(0.0, total - duration)
                parts.append(
                    f"[{v_label}][{index}:v]xfade=transition={transition.kind}:"
                    f"duration={duration:.3f}:offset={offset:.3f}[{v_out}]"
                )
                parts.append(
                    f"[{a_label}][{index}:a]acrossfade=d={duration:.3f}:c1=tri:c2=tri[{a_out}]"
                )
                total += scene.duration - duration

        v_label, a_label = v_out, a_out

    # ---- post chain -------------------------------------------------------
    video_chain: list[str] = []
    audio_chain: list[str] = []

    lut = pipe.get("lut")
    if lut:
        lut_path = resolve(root, lut)
        if not lut_path.is_file():
            raise PipelineError(f"LUT not found: {lut_path}")
        # lut3d loads a .cube — colorchannelmixer cannot, it only does a 3x3 matrix.
        video_chain.append(f"lut3d=file='{escape_filter_value(lut_path)}'")

    video_chain.append(scale_pad(width, height))
    video_chain.append(f"fps={fps}")

    subtitles = pipe.get("subtitles")
    if subtitles:
        subs_path = resolve(root, subtitles)
        if not subs_path.is_file():
            raise PipelineError(f"Subtitle file not found: {subs_path}")
        style = pipe.get("subtitleStyle") or (
            "Alignment=2,FontName=Arial,FontSize=42,PrimaryColour=&H00FFFFFF,"
            "OutlineColour=&H00000000,BorderStyle=1,Outline=2,Shadow=0,MarginV=60"
        )
        video_chain.append(
            f"subtitles=filename='{escape_filter_value(subs_path)}':"
            f"force_style='{style}'"
        )

    fade_in = float(parse_time(pipe["fadeInFromBlack"])) if pipe.get("fadeInFromBlack") else 0.0
    if fade_in > 0:
        video_chain.append(f"fade=t=in:st=0:d={fade_in:.3f}")
        audio_chain.append(f"afade=t=in:st=0:d={fade_in:.3f}")

    # transition on the LAST scene = fade to black on the tail
    tail = scenes[-1].transition
    if not tail.is_cut:
        tail_duration = min(tail.duration, total - 0.05)
        if tail_duration > 0:
            start = max(0.0, total - tail_duration)
            video_chain.append(f"fade=t=out:st={start:.3f}:d={tail_duration:.3f}")
            audio_chain.append(f"afade=t=out:st={start:.3f}:d={tail_duration:.3f}")

    video_chain.append("format=yuv420p")
    parts.append(f"[{v_label}]{','.join(video_chain)}" +
                 ("[vpost]" if logo_index is not None else "[vout]"))

    if logo_index is not None:
        logo_height = max(24, int(height * float(pipe.get("logoScale", 0.07))))
        seconds = pipe.get("logoSeconds")
        enable = ""
        if seconds not in (None, "", "always"):
            enable = f":enable='between(t,0,{parse_time(seconds):.3f})'"
        margin = int(height * 0.035)
        parts.append(f"[{logo_index}:v]scale=-1:{logo_height}[wm]")
        parts.append(f"[vpost][wm]overlay=x={margin}:y={margin}{enable}[vout]")

    parts.append(f"[{a_label}]{','.join(audio_chain) if audio_chain else 'anull'}"
                 f",aresample=48000[aout]")

    return ";".join(parts), total


def stage_render(scenes: list[Scene], pipe: dict[str, Any], root: Path, out_file: Path, *,
                 dry_run: bool, limit: float | None, step: str) -> float:
    print(f"\n▸ {step} · render master")
    for scene in scenes:
        if scene.normalized is None:
            scene.normalized = (root / "tmp" / f"{scene.id}.norm.mp4").resolve()
        if not scene.normalized.is_file() and not dry_run:
            raise PipelineError(
                f"Missing intermediate {scene.normalized.name}. Run the trim stage first."
            )

    logo = pipe.get("logo")
    logo_path = resolve(root, logo) if logo else None
    if logo_path and not logo_path.is_file():
        raise PipelineError(f"Logo not found: {logo_path}")
    logo_index = len(scenes) if logo_path else None

    graph, total = build_filtergraph(scenes, pipe, root, logo_index)

    cap = parse_time(pipe["maxDuration"]) if pipe.get("maxDuration") else None
    if limit:
        cap = min(cap, limit) if cap else limit
    final_duration = min(total, cap) if cap else total
    if cap and total > cap:
        print(f"  ! capped at {timecode(cap)} (timeline is {timecode(total)})")

    args: list[str] = []
    for scene in scenes:
        args += ["-i", str(scene.normalized)]
    if logo_path:
        args += ["-i", str(logo_path)]

    args += ["-filter_complex", graph, "-map", "[vout]", "-map", "[aout]"]
    args += video_encoder_args(pipe)
    args += audio_encoder_args(pipe)
    if cap:
        args += ["-t", f"{final_duration:.3f}"]
    args += ["-movflags", "+faststart", str(out_file)]

    ensure_dir(out_file.parent)
    run_ffmpeg(args, label="render", total_seconds=final_duration, dry_run=dry_run)
    return final_duration


# --------------------------------------------------------------------------- #
# stage 3 — preview + thumbnail
# --------------------------------------------------------------------------- #

def stage_preview(pipe: dict[str, Any], out_file: Path, duration: float, *,
                  dry_run: bool, step: str) -> dict[str, str]:
    artifacts: dict[str, str] = {}
    print(f"\n▸ {step} · preview + thumbnail")

    preview_seconds = pipe.get("previewSeconds", 10)
    if pipe.get("preview", True) and preview_seconds:
        seconds = min(float(parse_time(preview_seconds)), max(1.0, duration))
        preview_path = out_file.with_name(f"{out_file.stem}_preview.mp4")
        run_ffmpeg(["-ss", "0", "-t", f"{seconds:.3f}", "-i", str(out_file),
                    "-c", "copy", "-movflags", "+faststart", str(preview_path)],
                   label="preview", dry_run=dry_run)
        artifacts["preview"] = preview_path.name

    at = pipe.get("thumbnailAt")
    position = float(parse_time(at)) if at else duration * 0.1
    position = min(max(0.0, position), max(0.0, duration - 0.1))
    thumb_path = out_file.with_name(f"{out_file.stem}_thumb.jpg")
    run_ffmpeg(["-ss", f"{position:.3f}", "-i", str(out_file), "-frames:v", "1",
                "-vf", "scale=1280:720:force_original_aspect_ratio=decrease,"
                       "pad=1280:720:(ow-iw)/2:(oh-ih)/2",
                "-q:v", "2", str(thumb_path)],
               label="thumbnail", dry_run=dry_run)
    artifacts["thumbnail"] = thumb_path.name
    return artifacts


# --------------------------------------------------------------------------- #
# stage 4 — upload
# --------------------------------------------------------------------------- #

def stage_upload(config: dict[str, Any], root: Path, out_file: Path,
                 thumbnail: Path | None, *, dry_run: bool, step: str) -> str | None:
    youtube = config.get("youtube") or {}
    if not youtube.get("upload"):
        print(f"\n▸ {step} · upload skipped (youtube.upload = false)")
        return None

    print(f"\n▸ {step} · upload")
    if dry_run:
        print(f"  [dry-run] would upload {out_file.name} as "
              f"{youtube.get('title')!r} ({youtube.get('privacy', 'private')})")
        return None

    from youtube_api import YouTubeUploader  # imported late: render needs no google libs

    uploader = YouTubeUploader(
        client_secrets=resolve(root, youtube.get("clientSecrets", "client_secrets.json")),
        token_path=resolve(root, youtube.get("tokenFile", "token.json")),
    )
    video_id = uploader.upload(
        video_path=out_file,
        title=youtube.get("title", out_file.stem),
        description=youtube.get("description", ""),
        tags=youtube.get("tags", []),
        privacy=youtube.get("privacy", "private"),
        category_id=youtube.get("categoryId", "22"),
        made_for_kids=bool(youtube.get("madeForKids", False)),
    )
    if thumbnail and thumbnail.is_file():
        uploader.set_thumbnail(video_id, thumbnail)
    return video_id


# --------------------------------------------------------------------------- #
# main
# --------------------------------------------------------------------------- #

def main() -> int:
    # Piped into a CI log, stdout is block-buffered while stderr is not, which
    # lands the failure line above the stage it belongs to. Line-buffer both.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(line_buffering=True)  # type: ignore[union-attr]
        except (AttributeError, ValueError):
            pass

    parser = argparse.ArgumentParser(description="houly-pipe long-form render pipeline")
    parser.add_argument("--config", default="config.yaml")
    parser.add_argument("--base", default=None,
                        help="directory relative paths resolve against "
                             "(default: the config file's own folder)")
    parser.add_argument("--dry-run", action="store_true", help="print commands, run nothing")
    parser.add_argument("--stages", default=",".join(ALL_STAGES),
                        help=f"comma-separated subset of {','.join(ALL_STAGES)}")
    parser.add_argument("--force-trim", action="store_true", help="ignore cached intermediates")
    parser.add_argument("--limit", type=float, default=None,
                        help="cap the master at N seconds (smoke tests)")
    parser.add_argument("--preset", default=None, help="override pipeline.preset")
    args = parser.parse_args()

    stages = [stage.strip() for stage in args.stages.split(",") if stage.strip()]
    unknown = [stage for stage in stages if stage not in ALL_STAGES]
    if unknown:
        raise PipelineError(f"Unknown stage(s): {', '.join(unknown)}")

    require_tools()
    config, root = load_config(args.config)
    # A config generated on the fly (the bridge writes one per job into
    # .bridge/configs/) does not sit next to the footage, so its own folder is
    # the wrong anchor for `raw/intro.mp4`. --base names the real project root.
    if args.base:
        root = Path(args.base).expanduser().resolve()
    pipe = config.get("pipeline") or {}
    if args.preset:
        pipe["preset"] = args.preset

    tmp = ensure_dir(resolve(root, pipe.get("tmpDir", "tmp")))
    out_file = resolve(root, pipe.get("outputFile", "out/final_render.mp4"))
    ensure_dir(out_file.parent)

    status: StatusWriter | None = None
    if not args.dry_run:
        # A requested upload stage that youtube.upload disables never runs, so
        # excluding it keeps the weights normalised — otherwise progress would
        # stall at 88% and jump to 100%.
        will_upload = bool((config.get("youtube") or {}).get("upload"))
        tracked = [stage for stage in stages if stage != "upload" or will_upload]
        status = StatusWriter(out_file.parent / "status.json", tracked)
        set_progress_hook(status.on_progress)

    started = time.monotonic()
    print(f"houly-pipe · {args.config}")
    scenes = build_scenes(config, root)
    timeline = sum(scene.duration for scene in scenes)
    keyed_count = sum(1 for scene in scenes if scene.composite)
    print(f"  {len(scenes)} scenes · {timecode(timeline)} before transitions"
          + (f" · {keyed_count} green screen" if keyed_count else ""))

    # Numbered against the stages this run will really execute, so `--stages
    # render` does not announce itself as "stage 3 of 5" and read as skipped work.
    planned = [stage for stage in ALL_STAGES if stage in stages]

    def step(stage: str) -> str:
        return f"stage {planned.index(stage) + 1}/{len(planned)}"

    if "composite" in stages:
        preflight_composites(scenes, root)
    if "render" in stages:
        preflight_assets(pipe, root)

    if "composite" in stages:
        stage_composite(scenes, pipe, tmp, root, dry_run=args.dry_run,
                        force=args.force_trim, step=step("composite"),
                        progress=status.on_progress if status else None)
    else:
        adopt_existing_keys(scenes, tmp)

    if "trim" in stages:
        stage_trim(scenes, pipe, tmp, dry_run=args.dry_run, force=args.force_trim,
                   step=step("trim"))
    else:
        for scene in scenes:
            scene.normalized = tmp / f"{scene.id}.norm.mp4"

    duration = timeline
    if "render" in stages:
        duration = stage_render(scenes, pipe, root, out_file, dry_run=args.dry_run,
                                limit=args.limit, step=step("render"))

    artifacts: dict[str, str] = {}
    if "preview" in stages and not args.dry_run and out_file.is_file():
        artifacts = stage_preview(pipe, out_file, duration, dry_run=args.dry_run,
                                  step=step("preview"))

    # ---- manifest (the dashboard reads this) ------------------------------
    if not args.dry_run and out_file.is_file():
        final = probe(out_file)
        manifest = {
            "generatedAt": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "output": out_file.name,
            "duration": final["duration"],
            "durationLabel": timecode(final["duration"]),
            "resolution": f"{final['width']}x{final['height']}",
            "fps": round(final["fps"], 3),
            "codec": final["vcodec"],
            "sizeBytes": out_file.stat().st_size,
            "sizeLabel": human_size(out_file.stat().st_size),
            "renderSeconds": round(time.monotonic() - started, 1),
            "scenes": [
                {
                    "id": scene.id,
                    "file": scene.source.name,
                    "start": timecode(scene.start),
                    "end": timecode(scene.start + scene.duration),
                    "duration": round(scene.duration, 3),
                    "transition": "cut" if scene.transition.is_cut
                                  else f"{scene.transition.kind} {scene.transition.duration:g}s",
                    **({"composited": str((scene.composite or {}).get("background"))}
                       if scene.composite else {}),
                }
                for scene in scenes
            ],
            **artifacts,
        }
        manifest_path = out_file.parent / "manifest.json"
        manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        print(f"\n✔ master   {out_file}  ({manifest['sizeLabel']}, "
              f"{manifest['durationLabel']}, {manifest['resolution']}@{manifest['fps']:g})")
        print(f"✔ manifest {manifest_path}")

    if "upload" in stages:
        thumb = out_file.with_name(f"{out_file.stem}_thumb.jpg")
        stage_upload(config, root, out_file, thumb, dry_run=args.dry_run,
                     step=step("upload"))

    if status:
        status.finish("done", out_file.name)

    print(f"\nTotal wall time {timecode(time.monotonic() - started)}")
    return 0


def _argv_value(flag: str) -> str | None:
    try:
        return sys.argv[sys.argv.index(flag) + 1]
    except (ValueError, IndexError):
        return None


def _status_path_from_argv() -> Path | None:
    """Best-effort out/status.json location, for reporting a top-level failure."""
    config_arg = _argv_value("--config") or "config.yaml"
    try:
        config, root = load_config(config_arg)
    except Exception:  # noqa: BLE001 - the real error is already being reported
        return None
    # Must mirror main(), or a failed bridge job writes its status where nobody looks.
    base = _argv_value("--base")
    if base:
        root = Path(base).expanduser().resolve()
    pipe = config.get("pipeline") or {}
    out_file = resolve(root, pipe.get("outputFile", "out/final_render.mp4"))
    return out_file.parent / "status.json"


def _report_failure(message: str) -> None:
    """Leave the failure in status.json so a watcher sees it without the console."""
    path = _status_path_from_argv()
    if path is None or not path.parent.is_dir():
        return
    try:
        path.write_text(json.dumps({
            "state": "failed",
            "error": message,
            "updatedAt": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        }, indent=2), encoding="utf-8")
    except OSError:
        pass


if __name__ == "__main__":
    try:
        sys.exit(main())
    except PipelineError as error:
        print(f"\n✖ {error}", file=sys.stderr)
        _report_failure(str(error))
        sys.exit(1)
    except KeyboardInterrupt:
        print("\n✖ interrupted", file=sys.stderr)
        _report_failure("interrupted")
        sys.exit(130)
